#!/usr/bin/env python3
"""Write core/src/robit_skins.rs: the Robit skins and how many textures each has, from the generated skin data
(src/datagen/generated/mekanism/data/mekanism/mekanism/robit_skin)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKINS = ROOT / "src/datagen/generated/mekanism/data/mekanism/mekanism/robit_skin"
OUT = ROOT / "mixins/mekanism/core/src/robit_skins.rs"

rows = [(f.stem, len(json.loads(f.read_text()).get("textures", []))) for f in sorted(SKINS.glob("*.json"))]
lines = ["//! Generated by tools/gen_robit_skins.py from the skin data: each skin and the number of its textures.", "",
         "pub const SKINS: &[(&str, usize)] = &["]
lines += [f'    ("{name}", {count}),' for name, count in rows]
lines += ["];", "",
          "/// How many textures the skin `key` (`mekanism:allay` or `allay`) has; the base skin's when it is unknown.",
          "pub fn textures(key: &str) -> usize {",
          "    let name = key.rsplit(':').next().unwrap_or(key);",
          "    SKINS.iter().find(|(n, _)| *n == name).map_or(2, |(_, c)| *c)",
          "}", "",
          "/// The name models are made under for the skin `key`: the key's name, or the base skin's when it is unknown.",
          "pub fn name(key: &str) -> &str {",
          "    let name = key.rsplit(':').next().unwrap_or(key);",
          "    if SKINS.iter().any(|(n, _)| *n == name) { name } else { \"robit\" }",
          "}", ""]
OUT.write_text("\n".join(lines))
