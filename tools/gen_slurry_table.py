#!/usr/bin/env python3
"""Write core/src/slurry_table.rs: Mekanism's dissolution, washing and crystallizing recipes, from the
generated recipe data (src/datagen/generated/mekanism/data/mekanism/recipe)."""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECIPES = ROOT / "src/datagen/generated/mekanism/data/mekanism/recipe"
OUT = ROOT / "mixins/mekanism/core/src/slurry_table.rs"


def recipes(kind):
    for path in sorted(RECIPES.rglob("*.json")):
        data = json.loads(path.read_text())
        if data.get("type") == f"mekanism:{kind}":
            yield data


def plain(ingredient):
    if ingredient.startswith("#"):
        raise ValueError(f"chemical tag ingredient {ingredient}")
    return ingredient


def main():
    lines = ["// Generated by tools/gen_slurry_table.py from Mekanism's recipe data; do not edit.", "",
             "use crate::nuclear::{CrystallizingRecipe, DissolutionRecipe, WashingRecipe};", ""]
    rows = []
    for r in recipes("dissolution"):
        item = r["item_input"]["ingredient"]
        assert item.startswith("#") and r["per_tick_usage"], r
        rows.append(f"    DissolutionRecipe {{ item_tag: {json.dumps(item[1:])}, count: {r['item_input']['count']}, "
                    f"chemical: {json.dumps(plain(r['chemical_input']['ingredient']))}, "
                    f"per_tick: {r['chemical_input']['amount']}, output: {json.dumps(r['output']['id'])}, "
                    f"amount: {r['output']['amount']} }},")
    lines += [f"pub const DISSOLUTION: [DissolutionRecipe; {len(rows)}] = [", *rows, "];", ""]
    rows = []
    for r in recipes("washing"):
        assert r["fluid_input"]["ingredient"] == "#minecraft:water", r
        rows.append(f"    WashingRecipe {{ input: {json.dumps(plain(r['chemical_input']['ingredient']))}, "
                    f"input_amount: {r['chemical_input']['amount']}, water: {r['fluid_input']['amount']}, "
                    f"output: {json.dumps(r['output']['id'])}, amount: {r['output']['amount']} }},")
    lines += [f"pub const WASHING: [WashingRecipe; {len(rows)}] = [", *rows, "];", ""]
    rows = []
    for r in recipes("crystallizing"):
        rows.append(f"    CrystallizingRecipe {{ input: {json.dumps(plain(r['input']['ingredient']))}, "
                    f"amount: {r['input']['amount']}, output: {json.dumps(r['output']['id'])}, "
                    f"count: {r['output'].get('count', 1)} }},")
    lines += [f"pub const CRYSTALLIZING: [CrystallizingRecipe; {len(rows)}] = [", *rows, "];", ""]
    OUT.write_text("\n".join(lines))
    subprocess.run(["rustfmt", "--edition", "2021", str(OUT)], check=True)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
